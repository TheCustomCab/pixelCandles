"""Make WLED's built-in web UI servable at /wled.htm (the Candles page owns /), with a way back.

The Candles page is uploaded as /index.htm, which replaces WLED's built-in UI at /. To keep WLED's own UI
reachable, this script takes the exact UI the firmware was built with (PAGE_index in WLED/wled00/html_ui.h,
gzip), applies three small patches, and writes a gzip file to upload as /wled.htm.gz.

Patch 1: WLED's UI treats any non-root page path as a reverse-proxy sub-folder (index.js onLoad: "detect
reverse proxy"), so at /wled.htm it would send every request to /wled.htm/json/... and fail to start
("Init failed: TypeError: lJson.shift is not a function"). The patch drops a trailing *.htm file name from
the path before that check, so /wled.htm behaves like /, while a real proxy sub-folder still works.
Patch 2 adds a Candles button (flame icon, amber) as the first button of WLED's top toolbar, which
stays on screen, linking back to the Candles page at /. Patch 3 lets the toolbar's buttons share its width
evenly on phones and tablets (WLED sizes them as fixed percentages, so a seventh button would wrap).

Run after building the firmware (html_ui.h is regenerated by the build), then upload
(CONTROLLER is the controller's address, <CONTROLLER_IP> in site.local.md):
    python3 tools/wled_ui.py
    curl -F "data=@WLED/build_output/wled.htm.gz;filename=/wled.htm.gz" http://$CONTROLLER/upload
If WLED's minified code changes, the script stops instead of uploading something unpatched.
"""
import gzip
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "WLED" / "wled00" / "html_ui.h"
OUT = ROOT / "WLED" / "build_output" / "wled.htm.gz"

# (old, new, why): each must match exactly once, or the script stops.
PATCHES = [
    ('.split("/");locproto=e.protocol',
     '.split("/");/\\.html?$/.test(s[s.length-1])&&s.pop();locproto=e.protocol',
     "treat /wled.htm like / instead of as a reverse-proxy folder"),
    ('<div class=btnwrap> <button onclick=togglePower()',
     '<div class=btnwrap> <button onclick=\'window.location.href=getURL("/")\' id=buttonCandles '
     'title="Back to the Candles page" style="color:#F2A93B"><i class=icons style="font-family:inherit">'
     '<svg width=24 height=24 viewBox="0 0 24 24" aria-hidden=true '
     'style="display:block;margin:0 auto;width:24px!important;height:24px!important">'
     '<path fill=currentColor d="M12 1c1.2 5.2-7.5 8-7.5 14.2a7.5 7.5 0 0 0 15 0c0-4-2.4-7-3.9-8.3.1 2.4-1.1 4.2'
     '-2.8 4.2-1.5 0-2.4-1.2-2.4-2.9C10.4 5.6 13.1 3.7 12 1z"/></svg></i>'
     '<p class=tab-label style="color:#F2A93B">Candles</p></button> <button onclick=togglePower()',
     "add a Candles button (back to the Candles page at /) at the start of WLED's top toolbar"),
    ('</style> </head>',
     '@media all and (max-width:1023px){.top .btnwrap{display:flex}'
     '.top .btnwrap button{flex:1 1 0;width:auto!important;min-width:0}}'
     '@media all and (max-width:479px){.top .btnwrap button{font-size:14px}}</style> </head>',
     "below 1024 px, share the toolbar evenly between the visible buttons so the extra one doesn't wrap"),
]


def main() -> int:
    text = SRC.read_text()
    length = int(re.search(r"PAGE_index_length = (\d+);", text).group(1))
    body = text[text.index("PAGE_index[] PROGMEM = {"):]
    body = body[body.index("{") + 1: body.index("};")]
    data = bytes(int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]{2}", body))
    if len(data) != length:
        print(f"PAGE_index is {len(data)} bytes, header says {length}", file=sys.stderr)
        return 1
    html = gzip.decompress(data).decode("utf-8")
    patched = html
    for old, new, why in PATCHES:
        if patched.count(old) != 1:
            print(f"patch '{why}': expected exactly one {old!r}, found {patched.count(old)}; "
                  "WLED's UI changed, update tools/wled_ui.py", file=sys.stderr)
            return 1
        patched = patched.replace(old, new)
    out = gzip.compress(patched.encode("utf-8"), compresslevel=9, mtime=0)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(out)
    print(f"{OUT.relative_to(ROOT)}: {len(out)} bytes, sha256 {hashlib.sha256(out).hexdigest()[:16]} "
          f"(from PAGE_index, {len(html)} bytes of HTML)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
